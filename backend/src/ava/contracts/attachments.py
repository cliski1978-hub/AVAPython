"""Contract definitions for AVA attachment metadata.

Framework-neutral DTOs. Vendor SDK objects must never appear here.

The enums below are the AVA-owned vocabulary the metadata record and wire
contracts reuse. Attachment identity (``attachment_id``) is always AVA-owned
and generated by the service. Clients never supply ids. ``created_at`` is an
authoritative, timezone-aware UTC value produced by the backend service;
arbitrary client timestamps are not trusted.

The wire responses (Step 4.14.F) deliberately exclude the physical
``storage_key``: it is an opaque reference interpreted only by content
adapters, so it is never exposed to clients (audit §7). Bytes travel
exclusively through ``GET /attachments/{attachment_id}/content``.
"""

from datetime import datetime
from enum import StrEnum

from pydantic import BaseModel, Field

from ava.contracts.version import CONTRACT_VERSION

# ============================================================
# BEGIN: Attachment vocabulary
# ============================================================


class AttachmentOwnerType(StrEnum):
    """AVA entities an attachment may be associated with.

    A generic owner model (owner type + owner id) keeps the metadata
    foundation extensible: a future workspace/tool-output owner is a new
    enum member, not a schema change. Unassociated attachments are allowed
    through a nullable owner pair. Workspace, run, agent, and RAG owners are
    deliberately absent until a concrete workflow needs them.
    """

    DOCUMENT = "document"
    CONVERSATION = "conversation"
    MESSAGE = "message"


class AttachmentStatus(StrEnum):
    """AVA attachment lifecycle status.

    Upload is two-resource work (metadata + physical content), so ``PENDING``
    marks a record whose content has not yet been finalized:
    ``available ⇒ content exists and its stored size matches``. ``FAILED``
    marks a recoverable/reportable failure. Deleted/archived/quarantined
    statuses are deferred until those workflows exist.
    """

    PENDING = "pending"
    AVAILABLE = "available"
    FAILED = "failed"


# ============================================================
# END: Attachment vocabulary
# ============================================================


# ============================================================
# BEGIN: Attachment Responses
# ============================================================


class AttachmentResponse(BaseModel):
    """Response contract describing an AVA attachment (Step 4.14.F).

    The wire shape is deliberately smaller than the stored metadata record:
    ``storage_key`` is an opaque physical-content reference that only content
    adapters interpret, so it is never exposed to clients (audit §7). Bytes
    travel exclusively through ``GET /attachments/{attachment_id}/content``.
    ``size_bytes`` is the content store's authoritative stored size — never a
    client claim. ``created_at`` is backend-minted timezone-aware UTC; it is
    not trusted from clients.
    """

    attachment_id: str
    file_name: str
    media_type: str
    size_bytes: int
    owner_type: AttachmentOwnerType | None
    owner_id: str | None
    status: AttachmentStatus
    created_at: datetime
    contract_version: str = Field(default=CONTRACT_VERSION, frozen=True)


class AttachmentListResponse(BaseModel):
    """Response contract for the owner-scoped attachment collection (Step 4.14.F).

    Attachments are listed only for a concrete owner pair; there is no global
    attachment list. ``owner_type``/``owner_id`` echo the pair the query used,
    and ``attachments`` preserves the repository's stable insertion order.
    """

    contract_version: str = Field(default=CONTRACT_VERSION, frozen=True)
    owner_type: AttachmentOwnerType
    owner_id: str
    attachments: list[AttachmentResponse]


# ============================================================
# END: Attachment Responses
