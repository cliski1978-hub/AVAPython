# BEGIN: Document Responses
# ============================================================


class DocumentResponse(BaseModel):
    """Response contract describing an AVA document.

    ``content`` is the canonical serialized-HTML string. The response is a
    snapshot suitable for round-tripping into the frontend model
    (``AvaDocument``): ``title``, ``content`` (→ ``content.value``),
    ``created_at``/``updated_at`` (→ ISO timestamps).
    """

    document_id: str
    title: str
    content: str
    content_format: ContentFormat
    created_at: datetime
    updated_at: datetime
    contract_version: str = Field(default=CONTRACT_VERSION, frozen=True)


class DocumentListResponse(BaseModel):
    """Response contract for the document collection endpoint."""

    contract_version: str = Field(default=CONTRACT_VERSION, frozen=True)
    documents: list[DocumentResponse]


class DocumentRevisionResponse(BaseModel):
    """Response contract describing an immutable AVA document revision (Step 4.13.E).

    A revision is a full snapshot of the document at a point in time:
    ``title``/``content``/``content_format`` replay the exact stored state and
    ``created_at`` is the snapshot UTC timestamp. ``revision_number`` is the
    per-document history sequence (1, 2, 3, …); it is a document-history value
    and must never be confused with ``contract_version``, which is the AVA
    transport schema version and stays constant across revisions.
    """

    revision_id: str
    document_id: str
    revision_number: int
    title: str
    content: str
    content_format: ContentFormat
    created_at: datetime
    contract_version: str = Field(default=CONTRACT_VERSION, frozen=True)


class DocumentRevisionListResponse(BaseModel):
    """Response contract for a document's revision-history collection (Step 4.13.E).

    Revisions are returned in ``revision_number`` ascending order
    (1, 2, 3, …) — the order the repository already guarantees, never sorted
    by timestamp. A known document with no revisions yields an empty list.
    """

    contract_version: str = Field(default=CONTRACT_VERSION, frozen=True)
    document_id: str
    revisions: list[DocumentRevisionResponse]


