"""Contract definitions for AVA documents.

Framework-neutral DTOs. Vendor SDK objects must never appear here.

Document identity (``document_id``) is always AVA-owned and generated by the
service. Clients never supply ids. Timestamps are authoritative,
timezone-aware UTC values produced by the backend service; arbitrary client
timestamps are never trusted.

Content is the canonical serialized-HTML string the frontend editor already
produces, transported flat as ``content`` + ``content_format`` rather than as
an editor object. Tiptap/ProseMirror structures never cross this boundary,
and content safety is enforced by the AVA HTML content policy (service
layer) before anything becomes trusted backend content.
"""

from datetime import datetime
from enum import StrEnum
from typing import Self

from pydantic import BaseModel, Field, field_validator, model_validator

from ava.contracts.version import CONTRACT_VERSION

# ============================================================
# BEGIN: Content Format
# ============================================================


class ContentFormat(StrEnum):
    """AVA-owned document content formats.

    ``HTML`` is the only canonical format today — it is what the frontend
    editor serializes (``DocumentContent.format == "html"``). The enum is the
    AVA-owned vocabulary future formats (e.g. Markdown) would extend.
    """

    HTML = "html"


# ============================================================
# END: Content Format
# ============================================================


# ============================================================
# BEGIN: Document Requests
# ============================================================


class CreateDocumentRequest(BaseModel):
    """Request contract for creating an AVA document.

    A title is optional: when omitted (or blank) the service assigns the
    frontend-compatible default ``"Untitled Document"``. ``content`` is
    required (a new document always has at least an empty paragraph) and is
    validated by the AVA HTML content policy in the service layer before
    storage.
    """

    title: str | None = None
    content: str = Field(min_length=1)
    content_format: ContentFormat = ContentFormat.HTML
    contract_version: str = Field(default=CONTRACT_VERSION, frozen=True)

    @field_validator("content")
    @classmethod
    def content_must_not_be_blank(cls, value: str) -> str:
        """Reject document content that is empty or only whitespace."""
        if not value.strip():
            raise ValueError("content must not be blank")
        return value


class UpdateDocumentRequest(BaseModel):
    """Request contract for updating an AVA document (title and/or content).

    At least one of ``title`` / ``content`` must be present. When ``content``
    is provided, ``content_format`` may optionally confirm the format
    (defaults to ``html``).
    """

    title: str | None = None
    content: str | None = None
    content_format: ContentFormat | None = None
    contract_version: str = Field(default=CONTRACT_VERSION, frozen=True)

    @field_validator("title")
    @classmethod
    def title_must_not_be_blank_when_present(cls, value: str | None) -> str | None:
        """Reject a provided title that is empty or only whitespace."""
        if value is not None and not value.strip():
            raise ValueError("title must not be blank")
        return value

    @field_validator("content")
    @classmethod
    def content_must_not_be_blank_when_present(cls, value: str | None) -> str | None:
        """Reject provided content that is empty or only whitespace."""
        if value is not None and not value.strip():
            raise ValueError("content must not be blank")
        return value

    @model_validator(mode="after")
    def at_least_one_field_must_be_present(self) -> Self:
        """Reject an update that mutates nothing."""
        if self.title is None and self.content is None:
            raise ValueError("at least one of title or content must be provided")
        return self


