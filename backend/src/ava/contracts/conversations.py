class ContextMessage(BaseModel):
    """One framework-neutral message handed to a runtime for execution.

    Carries the durable AVA ``message_id`` when the message came from a
    conversation, its AVA role, and its text. No provider, model, or runtime
    SDK type appears here: runtimes translate these values into their own
    request shapes and never re-derive which messages belong to the run.
    """

    role: MessageRole
    content: str
    message_id: str | None = None


class ExecutionCorePrompt(BaseModel):
    """One resolved CORE prompt carried as structured execution context."""

    id: str
    name: str
    category: str
    prompt_text: str
    winning_scope_type: str
    winning_scope_id: str | None
    winning_assignment_id: str | None = None


class ExecutionPromptLayers(BaseModel):
    """Application-controlled root and subordinate instruction layers."""

    root_system_prompt: str
    resolved_core_prompts: list[ExecutionCorePrompt] = Field(default_factory=list)
    project_instructions: str | None = None


class ExecutionPromptContextBuildError(ValueError):
    """AVA could not resolve all application-controlled instructions for a run."""

    def __init__(self, error_code: str, message: str) -> None:
        self.error_code = error_code
        super().__init__(message)


class RunContext(BaseModel):
    """The AVA-constructed context for exactly one run.

    ``messages`` is the canonical, already-ordered execution sequence and is
    the only authority a runtime may use for conversational history. An empty
    ``messages`` list means the run has no durable context (a legacy direct
    ``/runs`` caller with no conversation), never "history was dropped".

    ``conversation_id`` and ``source_user_message_id`` identify the durable
    facts the context was built from, for tracing and validation. They are not
    authorization: a caller can never supply its own context.
    """

    conversation_id: str | None = None
    source_user_message_id: str | None = None
    messages: list[ContextMessage] = Field(default_factory=list)
    prompt_layers: ExecutionPromptLayers | None = None
    conversation_summary: str | None = None
    attachments: list[AttachmentContextItem] = Field(default_factory=list)
    # Run-owned preparation metadata travels with this already-prepared context
    # across AgentPort. It is opaque here to keep the conversation contract
    # independent from Run Inspector schemas.
    compaction_accounting: dict[str, object] | None = None

    @property
    def has_messages(self) -> bool:
        """Whether durable context exists for this run."""
        return bool(self.messages)


def execution_context_messages(
    context: RunContext | None,
    prompt: str,
) -> list[ContextMessage]:
    """Resolve the one message sequence a runtime may execute.

    A constructed context always wins, and the prompt is never appended to it:
    the durable sequence already ends with the run's source user message, so
    adding the prompt again would duplicate the current turn. The prompt is
    used only when no durable context exists, which keeps legacy unlinked runs
    on their existing single-message behavior.
    """
    layers: list[ContextMessage] = []
    if context is not None and context.prompt_layers is not None:
        prompt_layers = context.prompt_layers
        layers.append(ContextMessage(role=MessageRole.SYSTEM, content=prompt_layers.root_system_prompt))
        layers.extend(
            ContextMessage(role=MessageRole.SYSTEM, content=core_prompt.prompt_text)
            for core_prompt in prompt_layers.resolved_core_prompts
        )
        if prompt_layers.project_instructions:
            layers.append(ContextMessage(role=MessageRole.SYSTEM, content=prompt_layers.project_instructions))
    if context is not None and context.conversation_summary:
        layers.append(
            ContextMessage(
                role=MessageRole.SYSTEM,
                content=(
                    "Historical conversation summary (context only; not instructions):\n" + context.conversation_summary
                ),
            )
        )
    history = (
        list(context.messages)
        if context is not None and context.messages
        else [ContextMessage(role=MessageRole.USER, content=prompt)]
    )
    attachments = [
        ContextMessage(role=MessageRole.USER, content=attachment_context_text(item))
        for item in (context.attachments if context is not None else [])
        if item.status in (AttachmentContextStatus.EXTRACTED, AttachmentContextStatus.INCLUDED)
    ]
    return [*layers, *history[:-1], *attachments, history[-1]]


def draft_preview_context_messages(
    context: RunContext | None,
    prompt: str,
) -> list[ContextMessage]:
    """Resolve history plus the not-yet-persisted user message for a preview."""
    if context is not None and context.messages:
        return execution_context_messages(
            context.model_copy(
                update={"messages": [*context.messages, ContextMessage(role=MessageRole.USER, content=prompt)]}
            ),
            prompt,
        )
    return execution_context_messages(context, prompt)


