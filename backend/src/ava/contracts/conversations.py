"""Contract definitions for AVA conversations and messages.

Framework-neutral DTOs. Vendor SDK objects must never appear here.

Conversation and message identity (``conversation_id`` / ``message_id``) is
always AVA-owned and generated by the service. Clients never supply ids.
Timestamps are authoritative, timezone-aware UTC values produced by the
backend service — arbitrary client timestamps are not trusted as creation or
update times.

The role/status vocabulary mirrors the frontend reducer's message shape
(``user``/``assistant``/``system`` and ``pending``/``complete``/``failed``/
``cancelled``) so a future client mapping is 1:1; these are AVA-owned
backend enums, not the frontend TypeScript types.
"""

from datetime import datetime
from enum import StrEnum

from pydantic import BaseModel, Field, field_validator

from ava.contracts.version import CONTRACT_VERSION

# ============================================================
# BEGIN: Message vocabulary
# ============================================================


class MessageRole(StrEnum):
    """AVA message roles.

    Values match the frontend ``MessageRole`` membership exactly
    (``user``/``assistant``/``system``) so client mapping stays 1:1; the enum
    itself is backend-owned.
    """

    USER = "user"
    ASSISTANT = "assistant"
    SYSTEM = "system"


class MessageStatus(StrEnum):
    """AVA message status.

    ``PENDING`` is reserved for messages that await a terminal run outcome
    (future message-authoring). ``COMPLETE`` marks content that is final —
    the status a stored message receives today, since no authoring pipeline
    exists yet. Values match the frontend ``MessageStatus`` membership.
    """

    PENDING = "pending"
    COMPLETE = "complete"
    FAILED = "failed"
    CANCELLED = "cancelled"


# ============================================================
# END: Message vocabulary
# ============================================================


# ============================================================
# BEGIN: Conversation Requests
# ============================================================


class CreateConversationRequest(BaseModel):
    """Request contract for creating an AVA conversation.

    A title is optional: when omitted (or blank) the service assigns a
    default title, mirroring the frontend's auto-titled first conversation.
    """

    title: str | None = None
    contract_version: str = Field(default=CONTRACT_VERSION, frozen=True)


class UpdateConversationRequest(BaseModel):
    """Request contract for renaming an AVA conversation."""

    title: str
    contract_version: str = Field(default=CONTRACT_VERSION, frozen=True)

    @field_validator("title")
    @classmethod
    def title_must_not_be_blank(cls, value: str) -> str:
        """Reject titles that are empty or contain only whitespace."""
        if not value.strip():
            raise ValueError("title must not be blank")
        return value


class CreateMessageRequest(BaseModel):
    """Request contract for appending a message to a conversation.

    ``role`` defaults to ``user`` (the common append path); future
    orchestration may append assistant messages via the same contract.
    ``source_run_id`` carries the optional AVA run that produced the message
    — the minimum message/run linkage established in Step 4.4.
    """

    content: str = Field(min_length=1)
    role: MessageRole = MessageRole.USER
    source_run_id: str | None = None
    contract_version: str = Field(default=CONTRACT_VERSION, frozen=True)

    @field_validator("content")
    @classmethod
    def content_must_not_be_blank(cls, value: str) -> str:
        """Reject message content that is empty or only whitespace."""
        if not value.strip():
            raise ValueError("content must not be blank")
        return value


# ============================================================
# END: Conversation Requests
# ============================================================


# ============================================================
# BEGIN: Conversation Responses
# ============================================================


class ConversationResponse(BaseModel):
    """Response contract describing an AVA conversation."""

    conversation_id: str
    title: str
    created_at: datetime
    updated_at: datetime
    contract_version: str = Field(default=CONTRACT_VERSION, frozen=True)


class ConversationListResponse(BaseModel):
    """Response contract for the conversation collection endpoint."""

    contract_version: str = Field(default=CONTRACT_VERSION, frozen=True)
    conversations: list[ConversationResponse]


class MessageResponse(BaseModel):
    """Response contract describing an AVA message."""

    message_id: str
    conversation_id: str
    role: MessageRole
    content: str
    status: MessageStatus
    source_run_id: str | None = None
    created_at: datetime
    updated_at: datetime
    contract_version: str = Field(default=CONTRACT_VERSION, frozen=True)


class ConversationMessagesResponse(BaseModel):
    """Response contract for a conversation's message collection."""

    contract_version: str = Field(default=CONTRACT_VERSION, frozen=True)
    conversation_id: str
    messages: list[MessageResponse]


