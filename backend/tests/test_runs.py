"""Run API tests.

API-level coverage for the run transport layer: starting and cancelling runs
through ``POST /runs`` and ``POST /runs/{run_id}/cancel``, plus snapshot
retrieval through ``GET /runs/{run_id}`` and ``GET /runs/{run_id}/events``.
The routes must operate on AVA-owned contracts, delegate to ``RunService``,
and never touch concrete adapter internals.
"""

