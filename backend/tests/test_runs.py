def test_get_run_events_returns_completed_lifecycle() -> None:
    """A completed run must expose the normalized event sequence."""
    with make_client() as client:
        body = start_run(client, "Lifecycle")
        response = client.get(f"/runs/{body['run_id']}/events")
    assert response.status_code == 200
    events = response.json()
    assert [e["event_type"] for e in events] == [
        "run_started",
        "message_started",
        "message_content",
        "run_completed",
    ]
    assert all(e["run_id"] == body["run_id"] for e in events)
    assert events[3]["event_type"] == EventType.RUN_COMPLETED
    assert set(events[0]) == {
        "event_id",
        "run_id",
        "sequence",
        "event_type",
        "timestamp",
        "payload",
        "contract_version",
    }


