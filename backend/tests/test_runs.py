def test_internal_failure_maps_to_error_contract() -> None:
    """Unhandled internal failures must return the AVA ErrorResponse shape."""

    class FailingRunService:
        """A run service whose start always raises (tests the error path)."""

        async def start_run(self, request: RunRequest) -> RunResponse:
            raise RuntimeError("boom")

        async def cancel_run(self, run_id: str) -> RunResponse:
            raise RuntimeError("boom")

    app = create_app()
    app.state.run_service = FailingRunService()

    # raise_server_exceptions=False: the client must observe the mapped
    # ErrorResponse rather than the raw exception.
    with TestClient(app, raise_server_exceptions=False) as client:
        response = client.post("/runs", json={"prompt": "Hello"})

    assert response.status_code == 500
    body = response.json()
    assert body["error_code"] == "internal_error"
    assert body["category"] == "internal"
    assert body["recoverable"] is False
    assert "boom" not in response.text


