def test_get_run_events_for_failed_run() -> None:
    """A failed run must expose run_started → run_failed with a safe payload."""

    app = create_app()
    app.state.run_service = RunService(
        MockAgentAdapter(fail_on_prompt="force failure"),
        run_repository=RunStore(),
        run_event_repository=RunEventStore(),
    )

    async def start_failing_run() -> str:
        response: RunResponse = await app.state.run_service.start_run(
            RunRequest(prompt="force failure")
        )
        return response.run_id

    run_id = asyncio.run(start_failing_run())
    with TestClient(app) as client:
        run = client.get(f"/runs/{run_id}").json()
        events = client.get(f"/runs/{run_id}/events").json()

    assert run["status"] == "failed"
    assert [e["event_type"] for e in events] == [
        "run_started", "message_started", "run_failed",
    ]
    assert events[-1]["payload"]["error_code"] == "agent_failed"
    assert events[-1]["payload"]["recoverable"] is False


